// Convert a real circuit's GPS centre line (GeoJSON LineString, e.g. from
// https://github.com/bacinger/f1-circuits) into a game circuit file.
//
//   node tools/convert-circuit.mjs <in.geojson> <out.js> <EXPORT_NAME> [options as JSON]
//
// Options: { "reverse": false, "startShift": 0 (metres), "scale": auto (px/m),
//            "rMinPx": 144, "stepM": 20 }
// Steps: GPS to metres, optional reverse (keeping the start), resample, light
// smoothing, round corners tighter than rMinPx, scale to pixels. The scale
// defaults to 4.5 px/m adjusted so short and long circuits end up with laps of
// roughly similar length.
import fs from 'fs';

const [, , inFile, outFile, exportName, optArg] = process.argv;
const opt = { reverse: false, startShift: 0, rMinPx: 144, stepM: 20, ...(optArg ? JSON.parse(optArg) : {}) };

const gj = JSON.parse(fs.readFileSync(inFile, 'utf8'));
const feat = gj.features ? gj.features[0] : gj;
let ll = feat.geometry.coordinates.filter((p) => Number.isFinite(p[0]) && Number.isFinite(p[1]));
if (ll[0][0] === ll[ll.length - 1][0] && ll[0][1] === ll[ll.length - 1][1]) ll = ll.slice(0, -1);
const lat0 = ll.reduce((s, p) => s + p[1], 0) / ll.length;
const lon0 = ll.reduce((s, p) => s + p[0], 0) / ll.length;
const kx = Math.cos((lat0 * Math.PI) / 180) * 111320;
const ky = 110540;
let xy = ll.map((p) => [(p[0] - lon0) * kx, -(p[1] - lat0) * ky]);
if (opt.reverse) xy = [xy[0], ...xy.slice(1).reverse()];

function resample(p, step) {
  const n = p.length;
  const out = [p[0]];
  let acc = 0;
  for (let i = 0; i < n; i++) {
    const a = p[i];
    const b = p[(i + 1) % n];
    const d = Math.hypot(b[0] - a[0], b[1] - a[1]);
    let t = step - acc;
    while (t <= d) {
      out.push([a[0] + ((b[0] - a[0]) * t) / d, a[1] + ((b[1] - a[1]) * t) / d]);
      t += step;
    }
    acc = d - (t - step);
  }
  if (Math.hypot(out[out.length - 1][0] - out[0][0], out[out.length - 1][1] - out[0][1]) < step * 0.5) out.pop();
  return out;
}
const smooth = (q) =>
  q.map((v, i) => {
    const a = q[(i - 1 + q.length) % q.length];
    const b = q[(i + 1) % q.length];
    return [(a[0] + 2 * v[0] + b[0]) / 4, (a[1] + 2 * v[1] + b[1]) / 4];
  });
function radius(q, i, k) {
  const n = q.length;
  const a = q[(i - k + n) % n];
  const b = q[i];
  const c = q[(i + k) % n];
  const cr = (b[0] - a[0]) * (c[1] - a[1]) - (b[1] - a[1]) * (c[0] - a[0]);
  const d = Math.hypot(b[0] - a[0], b[1] - a[1]) * Math.hypot(c[0] - b[0], c[1] - b[1]) * Math.hypot(c[0] - a[0], c[1] - a[1]);
  return Math.abs(cr) < 1e-9 ? Infinity : d / (2 * Math.abs(cr));
}

let p = resample(xy, 8);
const lengthM = p.length * 8;
if (opt.startShift) {
  const k = Math.round(opt.startShift / 8);
  p = p.slice(k).concat(p.slice(0, k));
}
const scale = opt.scale || Math.min(5.2, Math.max(3.6, 4.5 * Math.sqrt(4300 / lengthM)));
const rMinM = opt.rMinPx / scale;
for (let k = 0; k < 3; k++) p = smooth(p);
for (let it = 0; it < 4000; it++) {
  let changed = 0;
  const q = p.map((v) => v.slice());
  for (let i = 0; i < p.length; i++) {
    if (radius(p, i, 3) < rMinM) {
      const a = p[(i - 1 + p.length) % p.length];
      const b = p[(i + 1) % p.length];
      q[i] = [p[i][0] + ((a[0] + b[0]) / 2 - p[i][0]) * 0.5, p[i][1] + ((a[1] + b[1]) / 2 - p[i][1]) * 0.5];
      changed++;
    }
  }
  p = q;
  if (!changed) break;
}
const pts = resample(p, opt.stepM).map(([x, y]) => [Math.round(x * scale), Math.round(y * scale)]);

const rows = [];
let line = '  ';
for (const [x, y] of pts) {
  const item = `[${x}, ${y}], `;
  if (line.length + item.length > 100) {
    rows.push(line.trimEnd());
    line = '  ';
  }
  line += item;
}
rows.push(line.trimEnd().replace(/,$/, ''));
const name = (feat.properties && feat.properties.Name) || exportName;
const src = `// ${name}. Generated by tools/convert-circuit.mjs from the bacinger/f1-circuits
// GeoJSON (MIT licence, https://github.com/bacinger/f1-circuits): ${Math.round(lengthM)} m of centre
// line at ${scale.toFixed(2)} px per metre, corners rounded to at least ${Math.round(rMinM)} m radius${opt.reverse ? ', reversed to race direction' : ''}.
// The first point is the start/finish line.
export const ${exportName} = [
${rows.join('\n')}
];
`;
fs.writeFileSync(outFile, src);
console.log(JSON.stringify({ out: outFile, points: pts.length, lengthM: Math.round(lengthM), scale: +scale.toFixed(2), rMinM: Math.round(rMinM) }));
